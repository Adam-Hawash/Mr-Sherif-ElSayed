export var VIDEO_OPENED_EVENT = 'mg_video_opened'

export function notifyVideoOpened() {
  try {
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent(VIDEO_OPENED_EVENT))
    }
  } catch (e) {}
}
