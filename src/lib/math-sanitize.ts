// PURPOSE: (2026-و33) منقّي رموز الرياضيات المشترك — طلب المستر:
//   «المساعد بيكتب حاجات غريبة قوي — خليه يكتب برموز المنصة اللي بتظهر للطلاب
//    بدل اللخبطة دي».
//   الموديلات بتحب تكتب LaTeX بعلامات دولار $\sqrt{5}$ وماركداون **(6)**
//   ودي بتظهر للطالب خام ووخة — عارض المنصة (FractionText) بيحوّل
//   \frac و ^ و \sqrt لكسور رأسية وأُس حقيقي من غير أي علامات دولار.
//   المنقّي بيتنفذ قبل العرض فالطالب ما يشوفش غير رموز نضيفة.
//   مشترك بين: المساعد الذكي + ملاحظات الاختيارات + ملاحظات التصحيح.

/*
 * sanitizeMathText — نضّف نص رد الموديل من كل الحاجات الخامة:
 *   $$x^2$$ و $x^2$  →  x^2          (علامات الدولار بتتشال والمحتوى يفضل)
 *   **(6)** و *نص*   →  (6) / نص     (ماركداون الغامق والمائل)
 *   3*4              →  3×4          (نجمة الضرب بين أرقام تبقى ×)
 *   \[ ... \] و \( ... \) → المحتوى  (أقواس LaTeX المحيطة)
 */
export function sanitizeMathText(t: string): string {
  var s = String(t || '')
  /* علامات الدولار (مفردة أو مزدوجة) بتتشال والمحتوى يفضل */
  s = s.replace(/\$\$([\s\S]*?)\$\$/g, '$1')
  s = s.replace(/\$([^$\n]{0,200}?)\$/g, '$1')
  s = s.replace(/\$\$/g, '').replace(/\$/g, '')
  /* ماركداون الغامق/المائل **نص** → النص لوحده */
  s = s.replace(/\*\*([\s\S]*?)\*\*/g, '$1')
  /* نجمة الضرب بين أرقام → × (3*4 → 3×4) قبل شيل أي بقايا */
  s = s.replace(/([0-9٠-٩])\s*\*\s*([0-9٠-٩a-zA-Z(])/g, '$1×$2')
  s = s.replace(/\*([\s\S]*?)\*/g, '$1').replace(/\*/g, '')
  /* أقواس LaTeX المحيطة \[ ... \] و \( ... \) بتتشال والمحتوى يفضل */
  s = s.replace(/\\\[([\s\S]*?)\\\]/g, '$1').replace(/\\\(([\s\S]*?)\\\)/g, '$1')
  return s.trim()
}

